# Writes sjis.lua, vanatell's cp932 <-> UTF-8 codec, from Python's cp932
# codec. Python 3 standard library only. From the addon folder:
#   python3 tools/gen_sjis.py
# The tables are checked against Python's encoder before anything is written,
# so a run that finishes wrote a codec that agrees with it.
import os
import re
import sys
import unicodedata

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = range(0x40, 0xFD)  # 189 slots; 0x7F is never a trail, so its slot stays empty
SLOT = 3                    # UTF-8 bytes per slot, NUL-padded

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sjis.lua')

LICENSE = '''--[[
VanaTell. Copyright (c) 2026 Rob Shelnutt. All rights reserved.
Proprietary software, licensed and not sold; not open source. See LICENSE
in this folder for what you may and may not do with it.
]]
'''

CODE = '''
-- Generated by tools/gen_sjis.py from Python's cp932 codec: do not edit by
-- hand. To change it, edit the script and run, from the addon folder:
--   python3 tools/gen_sjis.py

-- Shift-JIS for vanatell: FFXI's chat is Microsoft's cp932, the relay and
-- the phone speak UTF-8. Plain Lua 5.1, no Windower API.
--   sjis.decode(bytes) -> utf8      cp932 text to UTF-8
--   sjis.encode(utf8) -> bytes      UTF-8 text to cp932
--   sjis.decode_char(s, i) -> utf8, length   the one character at byte i
-- A byte or code with no character becomes '?', one per code.
-- Bytes 0x00-0x7F are ASCII both ways (0x5C stays '\\' and 0x7E '~'), and
-- 0xA1-0xDF are halfwidth katakana U+FF61-U+FF9F.
local sjis = {}

-- Filled in at the end of this file:
-- DOUBLE[lead] holds one 3-byte slot per trail byte 0x40-0xFC, the UTF-8 of
-- that code padded with NULs, or three NULs when it has no character. Lead
-- bytes with no characters at all have no row.
-- EXTRA maps UTF-8 that cp932 encodes but never decodes to (the wave dash
-- U+301C, say, which it writes as the fullwidth tilde's code).
local DOUBLE, EXTRA

local function is_lead(b)
  return (b >= 0x81 and b <= 0x9F) or (b >= 0xE0 and b <= 0xFC)
end

-- Halfwidth katakana: byte 0xA1-0xDF is U+FEC0 + byte.
local HALF = {}
for b = 0xA1, 0xDF do
  HALF[b] = b <= 0xBF and ('\\239\\189' .. string.char(b)) or ('\\239\\190' .. string.char(b - 0x40))
end

-- The UTF-8 of the character starting at byte i of s, and its length in
-- bytes. A lead byte takes the byte after it as its trail, unless that is
-- the end or a NUL; a two-byte code with no character is one '?'.
function sjis.decode_char(s, i)
  local b = s:byte(i)
  if b < 0x80 then return string.char(b), 1 end
  if HALF[b] then return HALF[b], 1 end
  if not is_lead(b) then return '?', 1 end
  local t = s:byte(i + 1)
  if not t or t == 0 then return '?', 1 end
  local row = DOUBLE[b]
  if row and t >= 0x40 and t <= 0xFC then
    local k = (t - 0x40) * 3
    local c1, c2, c3 = row:byte(k + 1, k + 3)
    if c1 ~= 0 then
      return row:sub(k + 1, k + (c3 ~= 0 and 3 or c2 ~= 0 and 2 or 1)), 2
    end
  end
  return '?', 2
end

function sjis.decode(bytes)
  local out, i, n = {}, 1, #bytes
  while i <= n do
    local char, len = sjis.decode_char(bytes, i)
    out[#out + 1] = char
    i = i + len
  end
  return table.concat(out)
end

-- UTF-8 -> cp932, built on first use. Where several codes decode to the same
-- character, the lowest code wins, as Python's cp932 encoder has it.
local encoding

local function encode_table()
  if encoding then return encoding end
  local t = {}
  for b, char in pairs(HALF) do t[char] = string.char(b) end
  for lead = 0x81, 0xFC do
    local row = DOUBLE[lead]
    if row then
      for trail = 0x40, 0xFC do
        local k = (trail - 0x40) * 3
        local c1, c2, c3 = row:byte(k + 1, k + 3)
        if c1 ~= 0 then
          local char = row:sub(k + 1, k + (c3 ~= 0 and 3 or c2 ~= 0 and 2 or 1))
          if not t[char] then t[char] = string.char(lead, trail) end
        end
      end
    end
  end
  for char, code in pairs(EXTRA) do
    if not t[char] then t[char] = code end
  end
  encoding = t
  return t
end

-- Bytes in a UTF-8 sequence, from its first byte; nil if it cannot start one.
local function sequence_length(b)
  if b < 0x80 then return 1 end
  if b >= 0xC2 and b <= 0xDF then return 2 end
  if b >= 0xE0 and b <= 0xEF then return 3 end
  if b >= 0xF0 and b <= 0xF4 then return 4 end
  return nil
end

-- Each UTF-8 character cp932 has becomes its code; any other character
-- (emoji, say) and each malformed byte becomes '?'.
function sjis.encode(text)
  local t = encode_table()
  local out, i, n = {}, 1, #text
  while i <= n do
    local b = text:byte(i)
    local len = sequence_length(b)
    if len == 1 then
      out[#out + 1] = string.char(b)
    elseif len and i + len - 1 <= n and not text:sub(i + 1, i + len - 1):find('[^\\128-\\191]') then
      out[#out + 1] = t[text:sub(i, i + len - 1)] or '?'
    else
      out[#out + 1] = '?'; len = 1
    end
    i = i + len
  end
  return table.concat(out)
end
'''


def check(cond, message):
    if not cond:
        sys.exit('gen_sjis: ' + message)


def decoded_table():
    table = {}
    for lead in LEADS:
        for trail in TRAILS:
            code = bytes([lead, trail])
            try:
                char = code.decode('cp932')
            except UnicodeDecodeError:
                continue
            check(len(char) == 1, 'code %s decodes to more than one character' % code.hex())
            check(0x80 <= ord(char) <= 0xFFFF, 'code %s decodes outside U+0080-U+FFFF' % code.hex())
            table[code] = char
    return table


# Characters written into sjis.lua as decimal escapes rather than as UTF-8:
# private use, invisible or combining ones, and any that NFC normalisation
# would change if an editor saved the file.
def needs_escape(char):
    if unicodedata.category(char) in ('Cc', 'Cf', 'Co', 'Cn', 'Cs', 'Zs', 'Zl', 'Zp', 'Mn', 'Me'):
        return True
    return unicodedata.normalize('NFC', char) != char


def lua_bytes(char):
    data = char.encode('utf-8')
    if needs_escape(char):
        return ''.join('\\%d' % b for b in data)
    return char


def row_literal(lead, table):
    parts = []
    for trail in TRAILS:
        char = table.get(bytes([lead, trail]))
        if char is None:
            parts.append('\\0\\0\\0')
        else:
            pad = SLOT - len(char.encode('utf-8'))
            parts.append(lua_bytes(char) + '\\0' * pad)
    literal = ''.join(parts)
    # Every escape is \0 or a byte 128-255, never run into a following digit.
    for escape in re.findall(r'\\([0-9]+)', literal):
        check(escape == '0' or (len(escape) == 3 and 128 <= int(escape) <= 255),
              'row %02X: escape \\%s runs into a digit' % (lead, escape))
    return literal


def main():
    table = decoded_table()

    # Single bytes, as sjis.lua handles them without tables.
    for b in range(0x80):
        check(bytes([b]).decode('cp932') == chr(b), 'byte %02x is not ASCII' % b)
    for b in range(0xA1, 0xE0):
        check(bytes([b]).decode('cp932') == chr(0xFEC0 + b), 'byte %02x is not U+FEC0 + byte' % b)

    # The lowest code for each character, which is what the Lua encoder picks.
    lowest = {}
    for code in sorted(table):
        lowest.setdefault(table[code], code)
    for char, code in lowest.items():
        check(char.encode('cp932') == code, 'Python encodes U+%04X as %s, not %s'
              % (ord(char), char.encode('cp932').hex(), code.hex()))

    # Characters Python's cp932 encodes to a double-byte code but no code
    # decodes to.
    singles = {chr(b) for b in range(0x80)} | {chr(0xFEC0 + b) for b in range(0xA1, 0xE0)}
    extra = {}
    for cp in range(0x80, 0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        if char in lowest or char in singles:
            continue
        try:
            code = char.encode('cp932')
        except UnicodeEncodeError:
            continue
        if len(code) == 2:
            check(code in table, 'U+%04X encodes to %s, which decodes to nothing' % (cp, code.hex()))
            extra[char] = code

    lines = [LICENSE, CODE]
    lines.append('\nDOUBLE = {\n')
    rows = 0
    for lead in LEADS:
        if not any(bytes([lead, trail]) in table for trail in TRAILS):
            continue
        rows += 1
        lines.append("  [0x%02X] = '%s',\n" % (lead, row_literal(lead, table)))
    lines.append('}\n\nEXTRA = {\n')
    for char in sorted(extra):
        code = extra[char]
        lines.append("  ['%s'] = '\\%d\\%d', -- U+%04X -> %s, %s\n"
                     % (lua_bytes(char), code[0], code[1], ord(char), code.hex().upper(), table[code]))
    lines.append('}\n\nreturn sjis\n')

    text = ''.join(lines)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d codes in %d rows, %d extra, %d bytes'
          % (os.path.normpath(OUT), len(table), rows, len(extra), len(text.encode('utf-8'))))


if __name__ == '__main__':
    main()
