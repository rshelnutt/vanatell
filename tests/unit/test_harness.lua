local T = require('testlib')
T.test('real Lua 5.1 with no bit library', function()
  T.eq(_VERSION, 'Lua 5.1'); T.eq(rawget(_G, 'bit'), nil); T.eq(rawget(_G, 'jit'), nil)
  T.eq((pcall(require, 'bit')), false)
end)
T.test('luasocket and mime load', function()
  T.eq(type(require('socket').gettime()), 'number'); T.eq((require('mime').b64('foo')), 'Zm9v')
end)
T.test('windower stub records calls and fires events', function()
  local W = require('windower_stub').install()
  local got = {}
  windower.register_event('load', 'login', function(...) got[#got + 1] = {...} end)
  W.fire('login', 'x'); T.eq(got, {{'x'}})
  windower.register_event('incoming chunk', function() return true end)
  T.eq(W.fire('incoming chunk', 0x017, 'data'), true)
  windower.send_command('input /l hi'); T.eq(W.commands, {'input /l hi'})
  windower.add_to_chat(207, 'hello'); T.eq(W.chat, {{mode = 207, text = 'hello'}}); T.eq(W.lines(), {'hello'})
  T.eq(windower.ffxi.get_player().name, 'Me'); W.player = nil
  T.eq(windower.ffxi.get_player(), nil); T.eq(windower.ffxi.get_info().logged_in, false)
  T.eq(windower.addon_path, os.getenv('XR_ADDON_DIR'))
  T.eq(windower.ffxi.get_items(), nil); W.items = {[0] = {}}; T.eq(windower.ffxi.get_items(), {[0] = {}})
  W.install(); T.eq(windower.ffxi.get_items(), nil)
end)
T.test('extdata stub decodes what the test put on the item', function()
  local extdata = require('extdata')
  T.eq(extdata.decode({decoded = {type = 'Linkshell', name = 'A'}}), {type = 'Linkshell', name = 'A'})
  T.raises(function() extdata.decode({boom = 'bad extdata'}) end, 'bad extdata')
end)
T.test('config stub persists saves across loads', function()
  local config = require('config'); config._reset()
  local defaults = {url = '', token = '', enabled = true}
  local s = config.load(defaults); T.ok(s ~= defaults); T.eq(s.enabled, true)
  s.token = 'abc'; config.save(s, 'all')
  T.eq(config.load(defaults).token, 'abc'); T.eq(config._saves, {'all'}); T.eq(defaults.token, '')
end)
T.test('vendored rxi json handles relay frames', function()
  local json = T.addon('json')
  local f = json.decode('{"type":"send","id":123,"target":null,"text":"caf\\u00e9"}')
  T.eq(f.id, 123); T.eq(f.target, nil); T.eq(f.text, 'caf\195\169')
  T.eq(json.encode('a"b\n'), '"a\\"b\\n"'); T.eq(json.encode(1762800000000), '1762800000000')
  T.raises(function() json.decode('{bad') end, 'expected')
end)
T.test('T.eq raises on mismatch', function() T.raises(function() T.eq(1, 2) end, 'expected') end)
T.done()
