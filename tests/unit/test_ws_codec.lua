local T = require('testlib'); local ws = T.addon('ws')
local function hex(s) return (s:gsub('.', function(c) return ('%02x'):format(c:byte()) end)) end
T.test('xor table', function()
  T.eq(ws._xor(0x37, 0x48), 0x7f); T.eq(ws._xor(255, 255), 0); T.eq(ws._xor(0, 255), 255); T.eq(ws._xor(0xAA, 0x55), 0xFF)
end)
T.test('sha1 vectors including block boundaries', function()
  local v = {[''] = 'da39a3ee5e6b4b0d3255bfef95601890afd80709', abc = 'a9993e364706816aba3e25717850c26c9cd0d89d',
    abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq = '84983e441c3bd26ebaae4aa1f95129e5e54670f1',
    [('a'):rep(55)] = 'c1c8bbdc22796e28c0e15163d20899b65621d65a', [('a'):rep(56)] = 'c2db330f6083854c99d4b5bfb6e8f29f201be699',
    [('a'):rep(64)] = '0098ba824b5c16427bd7a1122a5a442a25ec644d', [('a'):rep(119)] = 'ee971065aaa017e0632a8ca6c77bb3bf8b1dfc56'}
  for input, digest in pairs(v) do T.eq(hex(ws._sha1(input)), digest, #input .. ' bytes') end
end)
T.test('base64 and RFC 6455 accept key', function()
  T.eq(ws._b64(''), ''); T.eq(ws._b64('f'), 'Zg=='); T.eq(ws._b64('fo'), 'Zm8='); T.eq(ws._b64('foobar'), 'Zm9vYmFy')
  T.eq(ws._accept_key('dGhlIHNhbXBsZSBub25jZQ=='), 's3pPLMBiTxaQ9kYGzzhZRbK+xOo=')
end)
T.test('encode frames (RFC 6455 5.7 examples)', function()
  T.eq(ws._encode_frame(1, 'Hello'), '\129\5Hello')
  T.eq(ws._encode_frame(1, 'Hello', '\55\250\33\61'), '\129\133\55\250\33\61\127\159\77\81\88')
  T.eq(ws._encode_frame(9, 'Hello'), '\137\5Hello')
  T.eq(ws._encode_frame(2, ('x'):rep(256)):sub(1, 4), '\130\126\1\0')
  T.eq(ws._encode_frame(2, ('x'):rep(65536)):sub(1, 10), '\130\127\0\0\0\0\0\1\0\0')
end)
T.test('decode frames', function()
  T.eq({ws._decode_frame('\129\5Hello', 100)}, {{fin = true, opcode = 1, masked = false, payload = 'Hello'}, 7})
  T.eq({ws._decode_frame('\129\133\55\250\33\61\127\159\77\81\88', 100)}, {{fin = true, opcode = 1, masked = true, payload = 'Hello'}, 11})
  T.eq(ws._decode_frame('\1\3Hel', 100).fin, false)
  T.eq(ws._decode_frame('\129\5Hel', 100), nil); T.eq(ws._decode_frame('\129', 100), nil)
  local f, n = ws._decode_frame('\130\126\1\0' .. ('x'):rep(256) .. 'rest', 1000); T.eq(#f.payload, 256); T.eq(n, 260)
  T.eq({ws._decode_frame('\129\11' .. ('z'):rep(11), 10)}, {false, 'frame too large'})
  T.eq({ws._decode_frame('\129\127\0\0\0\1\0\0\0\0', 2^40)}, {false, 'frame too large'})
end)
T.test('parse_url', function()
  T.eq(ws.parse_url('wss://relay.example.com'), {scheme = 'wss', host = 'relay.example.com', port = 443, path = '/', secure = true})
  T.eq(ws.parse_url('WSS://Relay.Example.com:8443/v1/ws?role=addon'), {scheme = 'wss', host = 'relay.example.com', port = 8443, path = '/v1/ws?role=addon', secure = true})
  T.eq(ws.parse_url('ws://localhost:8787/v1/ws?role=addon').secure, false)
  T.eq(ws.parse_url('ws://127.0.0.1:8787').port, 8787)
  T.eq(ws.parse_url('http://localhost:8787/v1/pair').port, 8787); T.eq(ws.parse_url('https://relay.example.com/v1/pair').port, 443)
  T.eq({ws.parse_url('ws://example.com')}, {nil, 'plain ws:// and http:// are only allowed for localhost'})
  T.eq({ws.parse_url('http://example.com/x')}, {nil, 'plain ws:// and http:// are only allowed for localhost'})
  T.eq({ws.parse_url('ftp://x')}, {nil, 'unsupported scheme'}); T.eq({ws.parse_url('wss://')}, {nil, 'missing host'})
  T.eq({ws.parse_url('wss://user@h')}, {nil, 'invalid host'}); T.eq({ws.parse_url('wss://h:0')}, {nil, 'invalid port'})
  T.eq({ws.parse_url('wss://h:70000')}, {nil, 'invalid port'})
end)
T.test('hostname verification', function()
  local function cert(san, cn)
    return {extensions = function() return san and {['2.5.29.17'] = san} or {} end,
            subject = function() return {{oid = '2.5.4.3', value = cn}} end}
  end
  T.eq(ws._verify_hostname(cert({dNSName = {'Relay.Example.com'}}), 'relay.example.com'), true)
  T.eq(ws._verify_hostname(cert({dNSName = {'*.example.com'}}), 'relay.example.com'), true)
  T.eq({ws._verify_hostname(cert({dNSName = {'*.example.com'}}), 'example.com')}, {nil, 'certificate hostname mismatch'})
  T.eq({ws._verify_hostname(cert({dNSName = {'*.example.com'}}), 'a.relay.example.com')}, {nil, 'certificate hostname mismatch'})
  T.eq({ws._verify_hostname(cert({dNSName = {'relay.example.com'}}, 'x.com'), 'x.com')}, {nil, 'certificate hostname mismatch'})
  T.eq(ws._verify_hostname(cert(nil, 'x.com'), 'x.com'), true)
  T.eq(ws._verify_hostname(cert({iPAddress = {'127.0.0.1'}}), '127.0.0.1'), true)
  T.eq({ws._verify_hostname(cert({dNSName = {'localhost'}}), '127.0.0.1')}, {nil, 'certificate hostname mismatch'})
end)
T.done()
