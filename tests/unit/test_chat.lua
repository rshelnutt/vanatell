local T = require('testlib'); local P = require('xr_packets'); local chat = T.addon('chat')
T.test('test_incoming_channels', function()
  T.eq(chat.parse_incoming(P.incoming_chat(3, 'Kupo', 'hey')), {channel = 'tell', sender = 'Kupo', text = 'hey'})
  T.eq(chat.parse_incoming(P.incoming_chat(5, 'Kupo', 'hi ls')).channel, 'ls1')
  T.eq(chat.parse_incoming(P.incoming_chat(27, 'Kupo', 'hi ls2')).channel, 'ls2')
  for _, m in ipairs({0, 1, 4, 26}) do T.eq(chat.parse_incoming(P.incoming_chat(m, 'Kupo', 'x')), nil) end
  T.eq(chat.parse_incoming(P.incoming_chat(3, '', 'hey')), nil)
  T.eq(chat.parse_incoming(P.incoming_chat(3, 'Kupo', '\0')), nil)
  T.eq(chat.parse_incoming(('\0'):rep(0x16)), nil)
end)
T.test('test_sanitize', function()
  T.eq(chat.sanitize('hey\0\0\0junk'), 'hey')
  T.eq(chat.sanitize('\253\2\2\1\0\253 please'), '[AT] please')
  T.eq(chat.sanitize('\131\65bc'), '?bc')
  T.eq(chat.sanitize('\177x'), '?x')
  T.eq(chat.sanitize('\30\1red\31\5'), 'red')
  T.eq(chat.sanitize('a\7b'), 'ab'); T.eq(chat.sanitize('\253abc'), '?abc'); T.eq(chat.sanitize('  hi  \0'), 'hi')
  T.eq(chat.sanitize('\0'), nil); T.eq(chat.sanitize('   '), nil); T.eq(chat.sanitize('\30\1'), nil)
end)
T.test('test_outgoing_mirrors', function()
  T.eq(chat.parse_outgoing(0x0B5, P.outgoing_ls(5, 'hi all')), {channel = 'ls1', text = 'hi all'})
  T.eq(chat.parse_outgoing(0x0B5, P.outgoing_ls(27, 'hi all')).channel, 'ls2')
  T.eq(chat.parse_outgoing(0x0B5, P.outgoing_ls(0, 'say')), nil)
  T.eq(chat.parse_outgoing(0x0B6, P.outgoing_tell('Kupo', 'yo')), {channel = 'tell', target = 'Kupo', text = 'yo'})
  T.eq(chat.parse_outgoing(0x0B6, P.outgoing_tell('', 'yo')), nil)
  T.eq(chat.parse_outgoing(0x0B7, P.outgoing_ls(5, 'x')), nil)
end)
T.test('test_validate_send_commands', function()
  T.eq({chat.validate_send('tell', 'Kupo', 'on my way')}, {'input /tell Kupo on my way', 'on my way'})
  T.eq({chat.validate_send('ls1', nil, 'hi')}, {'input /l hi', 'hi'})
  T.eq({chat.validate_send('ls2', 'Ignored', 'hi')}, {'input /l2 hi', 'hi'})
  T.eq({chat.validate_send('say', nil, 'hi')}, {nil, 'invalid channel'})
  for _, t in ipairs({'Ku', 'Kupo1', 'Kupo Kupo', ('a'):rep(16), ''}) do
    T.eq({chat.validate_send('tell', t, 'hi')}, {nil, 'invalid target'})
  end
  T.eq({chat.validate_send('tell', nil, 'hi')}, {nil, 'invalid target'})
  T.eq((chat.validate_send('tell', ('a'):rep(15), 'hi')), 'input /tell ' .. ('a'):rep(15) .. ' hi')
end)
T.test('test_text_rules', function()
  T.eq({chat.validate_send('ls1', nil, 'a\r\nb\tc')}, {'input /l a b c', 'a b c'})
  T.eq({chat.validate_send('ls1', nil, 'a\1b\127c')}, {'input /l abc', 'abc'})
  T.eq({chat.validate_send('ls1', nil, '/shout hi')}, {nil, 'text must not start with /'})
  T.eq({chat.validate_send('ls1', nil, '  //lua unload vanatell')}, {nil, 'text must not start with /'})
  T.eq({chat.validate_send('ls1', nil, 'hi; lua unload vanatell')}, {'input /l hi, lua unload vanatell', 'hi, lua unload vanatell'})
  T.eq({chat.validate_send('ls1', nil, 'caf\195\169 \240\159\145\141')}, {'input /l caf? ?', 'caf? ?'})
  T.eq(select(2, chat.validate_send('ls1', nil, ('a'):rep(200))), ('a'):rep(150))
  T.eq(select(2, chat.validate_send('ls1', nil, ('a'):rep(149) .. ' b')), ('a'):rep(149))
  for _, s in ipairs({'', '   ', '\n'}) do T.eq({chat.validate_send('ls1', nil, s)}, {nil, 'empty text'}) end
  T.eq({chat.validate_send('ls1', nil, 42)}, {nil, 'invalid text'})
end)
T.done()
